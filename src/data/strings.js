// Helper function to get nested string values
export const getString = (path, fallback = '') => {
  const pathArray = path.split('.');
  let current = strings;
  
  for (const key of pathArray) {
    if (current && typeof current === 'object' && key in current) {
      current = current[key];
    } else {
      console.warn(`String path "${path}" not found`);
      return fallback;
    }
  }
  
  return typeof current === 'string' ? current : fallback;
};

// Helper function to get multiple strings at once
export const getStrings = (pathArray) => {
  return pathArray.reduce((acc, path) => {
    const key = path.split('.').pop(); // Use the last part as the key
    acc[key] = getString(path);
    return acc;
  }, {});
};

